async (page) => {
  const check = (value, message) => { if (!value) throw new Error(message) }
  const origin = 'http://127.0.0.1:5179'
  await page.setViewportSize({ width: 1280, height: 900 })
  check(await page.locator('.course-card').count() === 12, 'First page should contain 12 courses')
  check((await page.locator('.course-card').first().innerText()).includes('¥3,999'), 'Price must be in yuan')
  check((await page.locator('.course-card').first().innerText()).includes('90 天'), 'Duration must be in days')
  await page.screenshot({ path: 'output/playwright/course-catalog-desktop.png' })
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await page.getByText('第 2 / 3 页', { exact: true }).waitFor()
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await page.getByText('第 3 / 3 页', { exact: true }).waitFor()
  check(await page.locator('.course-card').count() === 1, 'Last page should contain one course')

  await page.getByRole('searchbox', { name: '课程名称' }).fill('retry')
  await page.getByRole('textbox', { name: '课程方向' }).fill('编程')
  await page.getByRole('combobox', { name: '我的学历' }).selectOption('2')
  await page.getByRole('combobox', { name: '排序方式' }).selectOption('price:desc')
  const filterRequest = page.waitForRequest((request) => request.url().includes('/api/v1/courses?') && request.url().includes('keyword=retry'))
  await page.getByRole('button', { name: '搜索课程', exact: true }).click()
  const filterUrl = new URL((await filterRequest).url())
  check(filterUrl.searchParams.get('edu') === '2' && filterUrl.searchParams.get('ascending') === 'false'
    && filterUrl.searchParams.get('type') === '编程' && filterUrl.searchParams.get('sortBy') === 'price', 'Search must pass all filters')
  await page.getByRole('alert').waitFor()
  const retryRequest = page.waitForRequest((request) => request.url().includes('/api/v1/courses?'))
  await page.getByRole('button', { name: '重新加载', exact: true }).click()
  check(new URL((await retryRequest).url()).searchParams.get('page') === '1', 'Retry must keep the failed request page')
  await page.getByText('第 1 / 1 页', { exact: true }).waitFor()
  console.log('PASS: pagination, filters, display units, failed-page retry')

  await page.getByRole('searchbox', { name: '课程名称' }).fill('empty')
  await page.getByRole('button', { name: '搜索课程', exact: true }).click()
  await page.getByRole('heading', { name: '没有找到符合条件的课程', exact: true }).waitFor()
  await page.getByRole('button', { name: '查看全部课程', exact: true }).click()
  await page.getByText('第 1 / 3 页', { exact: true }).waitFor()

  await page.setViewportSize({ width: 320, height: 900 })
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile list must not overflow horizontally')
  await page.screenshot({ path: 'output/playwright/course-catalog-mobile.png' })
  await page.getByRole('button', { name: '切换深色主题', exact: true }).click()
  check(await page.evaluate(() => document.documentElement.classList.contains('dark')), 'Dark mode should activate')
  await page.screenshot({ path: 'output/playwright/course-catalog-dark.png' })
  await page.getByRole('button', { name: '切换浅色主题', exact: true }).click()
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.locator('.course-card').first().click()
  await page.waitForURL(origin + '/courses/220331822288990209')
  await page.getByRole('heading', { name: 'Java 后端开发演示课程', exact: true }).waitFor()
  await page.screenshot({ path: 'output/playwright/course-detail-desktop.png' })
  console.log('PASS: empty state, 320px layout, dark theme, string ID detail navigation')
}
